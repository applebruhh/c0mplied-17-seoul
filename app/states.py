"""결제 1건당 4개 상태 축 (지침 결제흐름 4절) + 이벤트 이름."""
from enum import Enum


class AuthStatus(str, Enum):
    AUTHORIZED = "AUTHORIZED"
    DECLINED = "DECLINED"


class DeclineReason(str, Enum):
    LIMIT_EXCEEDED = "LIMIT_EXCEEDED"
    WALLET_BUSY = "WALLET_BUSY"
    # 아래는 '한도'가 아니라 요청 자체가 잘못된 경우 (지침의 한도 규칙과 별개)
    UNKNOWN_WALLET = "UNKNOWN_WALLET"
    PRICE_UNAVAILABLE = "PRICE_UNAVAILABLE"


class HoldStatus(str, Enum):
    NONE = "NONE"
    PLACED = "PLACED"
    RELEASED = "RELEASED"
    EXPIRED = "EXPIRED"


class LiqStatus(str, Enum):
    PENDING = "PENDING"
    IN_PROGRESS = "IN_PROGRESS"
    COMPLETED = "COMPLETED"
    FAILED = "FAILED"


class RecoveryStatus(str, Enum):
    UNRECOVERED = "UNRECOVERED"
    RECOVERED = "RECOVERED"
    LOSS_ABSORBED = "LOSS_ABSORBED"


class PayoutStatus(str, Enum):
    PENDING = "PENDING"
    SENT = "SENT"
    FAILED = "FAILED"


class LegStatus(str, Enum):
    PLANNED = "PLANNED"
    SUBMITTED = "SUBMITTED"     # 트랜잭션 제출됨 → TTL 지나도 잠금 유지
    CONFIRMED = "CONFIRMED"
    FAILED = "FAILED"


class Ev(str, Enum):
    AUTHORIZED = "AUTHORIZED"
    DECLINED = "DECLINED"
    HOLD_PLACED = "HOLD_PLACED"
    HOLD_RELEASED = "HOLD_RELEASED"
    HOLD_EXPIRED = "HOLD_EXPIRED"
    MERCHANT_PAYOUT_SENT = "MERCHANT_PAYOUT_SENT"
    MERCHANT_PAYOUT_FAILED = "MERCHANT_PAYOUT_FAILED"
    LIQUIDATION_STARTED = "LIQUIDATION_STARTED"
    SWAP_SUBMITTED = "SWAP_SUBMITTED"
    SWAP_CONFIRMED = "SWAP_CONFIRMED"
    SWAP_FAILED = "SWAP_FAILED"
    TREASURY_RECEIVED = "TREASURY_RECEIVED"
    LIQUIDATION_COMPLETED = "LIQUIDATION_COMPLETED"
    LIQUIDATION_FAILED = "LIQUIDATION_FAILED"
    REIMBURSEMENT_COMPLETED = "REIMBURSEMENT_COMPLETED"
    LOSS_ABSORBED = "LOSS_ABSORBED"
    STABLE_DEPEG_GUARD = "STABLE_DEPEG_GUARD"
    DAILY_CAP_RELAXED = "DAILY_CAP_RELAXED"
