#!/usr/bin/env python3
"""Generate/check shared schemas from Pydantic; no network or DB initialization."""
import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from pydantic.json_schema import models_json_schema
from app import models
from app.contracts import (CheckoutEventPayload, ErrorResponse, ExternalAuthorizeRequest,
                          ExternalAuthorizeResponse, SSEFrame)
from app.main import CapabilitiesResponse, HealthResponse, create_app

VERSION = "vaultpay.pos.v1"
EXPORTED = [models.CheckoutCreate, models.TapRequest, models.AuthorizationRequest,
            models.AuthorizationResult, models.EnginePayment, models.PaymentRead, models.CheckoutRead,
            models.CheckoutSnapshot, models.ActiveCheckoutResponse, models.TapResponse,
            models.PaymentsResponse, models.EventRead, models.ResetResponse,
            HealthResponse, CapabilitiesResponse, ExternalAuthorizeRequest, ExternalAuthorizeResponse,
            CheckoutEventPayload, ErrorResponse, SSEFrame]


def json_text(value):
    return json.dumps(value, indent=2, sort_keys=True, ensure_ascii=True) + "\n"


def ts_type(schema):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    for key in ("anyOf", "oneOf"):
        if key in schema:
            return " | ".join(ts_type(part) for part in schema[key])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts_type(schema.get('items', {}))}>"
    if kind == "object":
        if "properties" in schema:
            required = schema.get("required", [])
            fields = [f'{json.dumps(name)}{"" if name in required else "?"}: {ts_type(value)}'
                      for name, value in schema["properties"].items()]
            return "{ " + "; ".join(fields) + " }"
        additional = schema.get("additionalProperties", {})
        return f"Record<string, {ts_type(additional) if isinstance(additional, dict) else 'unknown'}>"
    return {"integer": "number", "number": "number", "string": "string",
            "boolean": "boolean", "null": "null"}.get(kind, "unknown")


def artifacts():
    _, schema = models_json_schema([(model, "validation") for model in EXPORTED], title=VERSION)
    types = [f"// GENERATED by scripts/freeze_contracts.py. Do not edit. Contract: {VERSION}",
             "// Runtime bounds/formats are defined by the checked-in JSON schemas.",
             f'export const CONTRACT_VERSION = "{VERSION}" as const;', ""]
    for name, definition in sorted(schema["$defs"].items()):
        types.append(f"export type {name} = {ts_type(definition)};\n")
    _, engine = models_json_schema(
        [(ExternalAuthorizeRequest, "validation"), (ExternalAuthorizeResponse, "validation")],
        title="SB Payment Engine authorization v1",
    )
    result = {
        "contracts/shared.schema.json": json_text(schema),
        "contracts/payment-engine.schema.json": json_text(engine),
        "contracts/pos.openapi.json": json_text(create_app().openapi()),
        "frontend/src/shared/contracts.ts": "\n".join(types),
    }
    manifest = {"contract_version": VERSION, "artifacts": {
        path: hashlib.sha256(content.encode()).hexdigest() for path, content in result.items()},
        "external_authorize": "POST /v1/payments/authorize",
        "external_lookup": "GET /v1/payments/{checkout_id}/pos",
        "signature_header": "X-SB-Signature", "signature_algorithm": "HMAC-SHA256-lowercase-hex",
        "uid_test_vector": {"uid": "04:a1:b2:c3:d4:e5:f6",
                            "card_token": "91ea67e855c23f69148746d73bf9c5d290227c0c4ab762f3fcc84713512d892b"}}
    result["contracts/freeze.json"] = json_text(manifest)
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail on drift without changing files")
    options = parser.parse_args()
    drift = []
    for name, content in artifacts().items():
        path = ROOT / name
        if options.check:
            if not path.exists() or path.read_text() != content:
                drift.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if drift:
        print("Shared contract drift: " + ", ".join(drift), file=sys.stderr)
        return 1
    print(f"{VERSION}: {'verified' if options.check else 'generated'} shared contracts")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
